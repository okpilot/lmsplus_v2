import { COLOURS, type ColourName } from './colour'
import { rem } from './fluid'
import {
  CONTAINERS,
  CONTROL_HEIGHT,
  DESKTOP_FROM,
  DURATIONS,
  EASING,
  ELEVATION,
  RADIUS,
  RADIUS_KEYS,
  SCRIM,
  SPACING,
  STATE,
  spacingValue,
  TRACKING_LOGO,
  TYPE_DESKTOP,
  TYPE_ROLES,
  typeSize,
  Z_INDEX,
} from './scale'

type Decl = readonly [name: string, value: string | number]

const block = (selector: string, decls: Decl[], indent = ''): string[] => [
  `${indent}${selector} {`,
  ...decls.map(([n, v]) => `${indent}  ${n}: ${v};`),
  `${indent}}`,
]

const colourDecls = (theme: 'light' | 'dark'): Decl[] =>
  (Object.keys(COLOURS.light) as ColourName[]).map((n) => [`--${n}`, COLOURS[theme][n]])

const shadow = (e: (typeof ELEVATION)[keyof typeof ELEVATION], a: number) =>
  `0 ${e.y}px ${e.blur}px oklch(0 0 0 / ${a}%)`

const elevationDecls = (theme: 'light' | 'dark'): Decl[] => [
  ['--elevation-raised', shadow(ELEVATION.raised, ELEVATION.raised[theme])],
  ['--elevation-overlay', shadow(ELEVATION.overlay, ELEVATION.overlay[theme])],
  ['--scrim', `oklch(0 0 0 / ${SCRIM[theme]}%)`],
]

function themeDecls(): Decl[] {
  const out: Decl[] = [['--text-*', 'initial']]
  for (const [role, r] of Object.entries(TYPE_ROLES)) {
    out.push([`--text-${role}`, typeSize(r)])
    out.push([`--text-${role}--line-height`, r.lineHeight])
    out.push([`--text-${role}--letter-spacing`, `${r.tracking}em`])
    out.push([`--text-${role}--font-weight`, r.weight])
  }
  out.push(['--tracking-logo', TRACKING_LOGO])
  for (const [name, range] of Object.entries(SPACING))
    out.push([`--spacing-${name}`, spacingValue(range)])
  for (const [name, v] of Object.entries(CONTAINERS)) out.push([`--container-${name}`, v])
  for (const k of RADIUS_KEYS) out.push([`--radius-${k}`, RADIUS[k]])
  for (const [name, z] of Object.entries(Z_INDEX)) out.push([`--z-index-${name}`, z])
  for (const [name, ms] of Object.entries(DURATIONS))
    out.push([`--transition-duration-${name}`, `${ms}ms`])
  for (const [name, v] of Object.entries(EASING)) out.push([`--ease-${name}`, v])
  out.push(['--default-transition-duration', 'var(--transition-duration-fast)'])
  out.push(['--default-transition-timing-function', 'var(--ease-standard)'])
  return out
}

const desktopDecls = (): Decl[] => [
  ['--control-h', CONTROL_HEIGHT.desktop],
  ...Object.entries(TYPE_DESKTOP).map(([r, px]): Decl => [`--text-${r}`, rem(px)]),
]

/** The whole of apps/web/app/tokens.css. Pure and deterministic. */
export function buildTokensCss(): string {
  const names = Object.keys(COLOURS.light) as ColourName[]
  const root: Decl[] = [
    ...colourDecls('light'),
    ...elevationDecls('light'),
    ['--radius', RADIUS.base],
    ['--control-h', CONTROL_HEIGHT.phone],
    ['--state-hover', STATE.hover],
    ['--state-pressed', STATE.pressed],
  ]
  const lines = [
    '/* Generated by apps/web/scripts/gen-tokens-css.ts from apps/web/lib/design — do not edit. */',
    ...block(':root', root),
    ...block('.dark', [...colourDecls('dark'), ...elevationDecls('dark')]),
    `@media (width >= ${DESKTOP_FROM}) {`,
    ...block(':root', desktopDecls(), '  '),
    '}',
    ...block('@theme inline', [
      ...names.map((n): Decl => [`--color-${n}`, `var(--${n})`]),
      ['--color-scrim', 'var(--scrim)'],
      ['--shadow-raised', 'var(--elevation-raised)'],
      ['--shadow-overlay', 'var(--elevation-overlay)'],
    ]),
    ...block('@theme', themeDecls()),
  ]
  return `${lines.join('\n')}\n`
}
