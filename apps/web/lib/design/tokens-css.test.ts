import { readFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'
import { buildTokensCss } from './build-tokens-css'
import { COLOURS, CONTRAST_PAIRS } from './colour'
import { contrastRatio } from './contrast'
import { Z_INDEX } from './scale'

const CSS_PATH = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../app/tokens.css')

describe('tokens.css', () => {
  it('matches the committed file byte for byte', () => {
    expect(readFileSync(CSS_PATH, 'utf8')).toBe(buildTokensCss())
  })

  it('starts with the generated-file banner and ends with a newline', () => {
    const css = buildTokensCss()
    expect(css.split('\n')[0]).toBe(
      '/* Generated by apps/web/scripts/gen-tokens-css.ts from apps/web/lib/design — do not edit. */',
    )
    expect(css.endsWith('}\n')).toBe(true)
  })

  it('declares every colour in light, dark and the Tailwind theme', () => {
    const css = buildTokensCss()
    const [lightPart, darkPart] = css.split('.dark {')
    expect(darkPart, 'tokens.css has a .dark block').toBeDefined()
    for (const name of Object.keys(COLOURS.light)) {
      expect(lightPart).toContain(
        `  --${name}: ${COLOURS.light[name as keyof typeof COLOURS.light]};`,
      )
      expect(darkPart).toContain(`  --${name}: ${COLOURS.dark[name as keyof typeof COLOURS.dark]};`)
      expect(css).toContain(`  --color-${name}: var(--${name});`)
    }
  })

  it('pins the success fill at the approved dashboard green', () => {
    expect(COLOURS.light['success-solid']).toBe('oklch(0.72 0.15 150)')
    expect(COLOURS.dark['success-solid']).toBe('oklch(0.74 0.14 150)')
  })
})

describe('neutral fill', () => {
  for (const theme of ['light', 'dark'] as const) {
    for (const surface of ['background', 'card', 'popover', 'overlay'] as const) {
      it(`muted stands apart from ${surface} in the ${theme} theme`, () => {
        const palette = COLOURS[theme]
        const ratio = contrastRatio(palette.muted, palette[surface])
        expect(
          ratio,
          `muted vs ${surface} (${theme}) = ${ratio.toFixed(3)}`,
        ).toBeGreaterThanOrEqual(1.08)
      })
    }
  }
})

const tint = (colour: string, pct: number) => colour.replace(/\)$/, ` / ${pct}%)`)

describe('text on translucent fills', () => {
  for (const theme of ['light', 'dark'] as const) {
    const p = COLOURS[theme]
    for (const under of ['background', 'card', 'popover', 'muted', 'accent'] as const) {
      for (const pct of [5, 10, 15]) {
        it(`primary-text on primary/${pct} over ${under} reaches 4.5:1 in the ${theme} theme`, () => {
          const ratio = contrastRatio(p['primary-text'], tint(p.primary, pct), p[under])
          expect(ratio, `${ratio.toFixed(2)}`).toBeGreaterThanOrEqual(4.5)
        })
      }
    }
    for (const pct of [30, 50, 80]) {
      it(`muted-foreground on muted/${pct} over card reaches 4.5:1 in the ${theme} theme`, () => {
        const ratio = contrastRatio(p['muted-foreground'], tint(p.muted, pct), p.card)
        expect(ratio, `${ratio.toFixed(2)}`).toBeGreaterThanOrEqual(4.5)
      })
    }
  }
})

describe('colour contrast', () => {
  for (const theme of ['light', 'dark'] as const) {
    for (const [fg, bg, min] of CONTRAST_PAIRS) {
      it(`${fg} on ${bg} reaches ${min}:1 in the ${theme} theme`, () => {
        const palette = COLOURS[theme]
        const ratio = contrastRatio(palette[fg], palette[bg], palette.background)
        expect(ratio, `${fg} on ${bg} (${theme}) = ${ratio.toFixed(2)}`).toBeGreaterThanOrEqual(min)
      })
    }
  }
})

describe('layers', () => {
  it('stacks menus above dialogs and the reload banner above toasts', () => {
    const { sticky, nav, overlay, dropdown, toast, banner } = Z_INDEX
    expect([sticky, nav, overlay, dropdown, toast, banner]).toEqual(
      [sticky, nav, overlay, dropdown, toast, banner].toSorted((a, b) => a - b),
    )
    expect(Z_INDEX.banner).toBeGreaterThan(Z_INDEX.toast)
    expect(new Set(Object.values(Z_INDEX)).size).toBe(6)
  })
})
